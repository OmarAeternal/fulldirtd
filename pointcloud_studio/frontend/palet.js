/** Tulis warna palet `nama` di t ∈ [0,1] ke out[o..o+2]. */
export function sampel(nama, t, out, o) {
  const J = PALET[nama] || PALET.viridis;
  const p = Math.min(1, Math.max(0, t)) * 32;
  const i = Math.min(31, Math.floor(p)), f = p - i;
  const a = J[i], b = J[i + 1];
  out[o] = a[0] + (b[0] - a[0]) * f;
  out[o + 1] = a[1] + (b[1] - a[1]) * f;
  out[o + 2] = a[2] + (b[2] - a[2]) * f;
}

